/**
 * Builds the content index (grammar IDs + per-level item totals) from the
 * repo's content files. Used by `npm run content:index` and by the drift test.
 * NOT imported at runtime: the server reads the generated `data/contentIndex.ts`.
 */
import fs from 'node:fs';
import path from 'node:path';

export const LEVELS = ['N5', 'N4', 'N3', 'N2', 'N1'] as const;

function readItems(file: string): Array<{ id?: string }> {
  const raw = JSON.parse(fs.readFileSync(file, 'utf-8'));
  if (Array.isArray(raw)) return raw;
  const list = raw?.items ?? raw?.stories ?? raw?.entries;
  return Array.isArray(list) ? list : [];
}

export interface ContentIndex {
  grammarIds: string[];
  totals: Record<string, { vocabulary: number; kanji: number; grammar: number; reading: number }>;
}

export function buildContentIndex(repoRoot: string): ContentIndex {
  const grammarIds: string[] = [];
  const totals: ContentIndex['totals'] = {};
  for (const level of LEVELS) {
    const n = level.toLowerCase();
    const grammar = readItems(path.join(repoRoot, 'content', 'grammar', `${n}.json`));
    grammarIds.push(...grammar.map((g) => g.id).filter((id): id is string => !!id));
    totals[level] = {
      vocabulary: readItems(path.join(repoRoot, 'content', 'vocabulary', `${n}.json`)).length,
      kanji: readItems(path.join(repoRoot, 'content', 'kanji', `${n}.json`)).length,
      grammar: grammar.length,
      reading: readItems(path.join(repoRoot, 'src', 'data', 'reading', `${n}_stories.json`)).length,
    };
  }
  return { grammarIds, totals };
}

/** Deterministic TypeScript source for the generated file. */
export function renderContentIndexModule(index: ContentIndex): string {
  return `// AUTO-GENERATED by \`npm run content:index\` (backend/scripts/generate-content-index.ts).
// Do not edit by hand. A test fails if this drifts from content/*.json.

export const GRAMMAR_IDS: readonly string[] = ${JSON.stringify(index.grammarIds)};

export const LEVEL_TOTALS: Record<string, { vocabulary: number; kanji: number; grammar: number; reading: number }> = ${JSON.stringify(index.totals, null, 2)};
`;
}
